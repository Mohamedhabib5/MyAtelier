    find_service_fn,
    is_no_dress_fn,
    money_fn,
    money_float_fn,
    add_payment_fn,
    dept_map,
    booking_status_active,
    note_booking_downpay,
    msg_dress_booked_same_date,
    msg_invalid_value,
